def render_form(template, values, approval):
    html = PLACEHOLDER_PATTERN.sub(
        lambda m: escape(values.get(m.group(1).strip(), '')).replace('\n', '<br>'),
        template['form_html'])
    return inject_approval_line(html, approval)


def build_values(profile_name, key):
    values = dict(BASE)
    values['작성자'] = profile_name
    values.update(FORM_VALUES[key])
    return values


def seed(db, client_id, manifest):
    client = db.get_client(client_id)
    owner = db.get_current_profile()
    owner_id = owner['id']
    db.ensure_builtin_templates(owner_id, TEMPLATES)

    # 다른 작성자의 서류가 열람 전용으로 열리는지 확인할 수 있게 보조 프로필을 만든다.
    dummy_owner = next((p['id'] for p in db.list_profiles() if p['name'] == DUMMY_PROFILE), None)
    if dummy_owner is None:
        dummy_owner = db.create_profile(DUMMY_PROFILE)
        manifest['worker_profiles'].append(dummy_owner)
    db.ensure_builtin_templates(dummy_owner, TEMPLATES)
    db.save_approval_line(dummy_owner, [{'title': '담당', 'name': DUMMY_PROFILE}, {'title': '팀장', 'name': '김팀장'}])

    # 결재라인이 비어 있을 때만 채운다. 기존 설정은 그대로 둔다.
    if not db.get_profile(owner_id).get('approval_line_json'):
        db.save_approval_line(owner_id, [{'title': '담당', 'name': owner['name']}, *APPROVAL_LINE[1:]])
        manifest['approval_line_set'] = owner_id

    templates = {t['source_key']: t for t in db.list_form_templates(owner_id)}
    dummy_templates = {t['source_key']: t for t in db.list_form_templates(dummy_owner)}

    # 1) 사례관리 서류 14종 (반복 작성 이력 포함 16건)
    for source_key, value_key, stage, record_date, status, by_dummy in CASE_FORMS:
        writer = dummy_owner if by_dummy else owner_id
        writer_name = DUMMY_PROFILE if by_dummy else owner['name']
        template = (dummy_templates if by_dummy else templates)[source_key]
        values = build_values(writer_name, value_key)
        snapshot = dict(db.make_template_snapshot(template))
        approval = db.get_approval_line(writer)
        snapshot['approval_steps'] = approval
        record_id = db.save_case_form(client_id, writer, {
            'source_key': source_key, 'stage': stage, 'record_date': record_date, 'status': status,
            'template_snapshot': snapshot, 'fields': values,
            'result_html': render_form(template, values, approval),
        })
        manifest['case_form_records'].append(record_id)

    # 2) 상담일지 (AI 작성 결과 형태)
    for item in COUNSELINGS:
        template = templates[item['template']]
        html = fill_form_html(template['form_html'], metadata={
            '대상자명': client['name'], '상담일자': item['date'],
            '작성자': owner['name'], '상담방법': item['method'],
        }, generated_text=item['result'])
        record_id = db.add_counseling_record({
            'client_id': client_id, 'session_date': item['date'], 'template_name': template['name'],
            'template_id': template['id'], 'template_snapshot': db.make_template_snapshot(template),
            'owner_id': owner_id, 'detail_level': item['detail'], 'raw_memo': item['memo'],
            'ai_result': item['result'],
            'result_html': inject_approval_line(html, db.get_approval_line(owner_id)),
            'worker_name': owner['name'], 'session_method': item['method'],
        })
        manifest['counseling_records'].append(record_id)

    # 3) 진행단계·사정·목표·모니터링
    previous = db.get_case_profile(client_id)
    manifest['case_profile_previous'] = {'stage': previous['stage'], 'stage_note': previous.get('stage_note', '')}
    db.save_case_profile(client_id, '사후관리', '2026-08-31 종결 후 사후관리 중. 11월 2차 확인 예정. ' + NOTE)

    for assessed_at, scores, summary in ASSESSMENTS:
        manifest['case_assessments'].append(db.add_assessment(client_id, scores, summary, assessed_at))

    for title, plan, due, progress, status in GOALS:
        goal_id = db.add_goal(client_id, title, plan, due)
        db.update_goal_progress(goal_id, progress, status)
        manifest['case_goals'].append(goal_id)

    for task_type, due, notes, done in MONITORING:
        task_id = db.add_monitoring_task(client_id, task_type, due, notes)
        if done:
            db.complete_monitoring_task(task_id)
        manifest['monitoring_tasks'].append(task_id)

    # 4) 지역자원과 서비스 연계
    resource_ids = [db.add_resource(*row) for row in RESOURCES]
    manifest['welfare_resources'].extend(resource_ids)
    for service_name, requested, status, result, resource_index in SERVICE_LINKS:
        link_id = db.add_service_link(client_id, resource_ids[resource_index], service_name, requested)
        db.update_service_link_status(link_id, status, result)
        manifest['service_links'].append(link_id)

    # 5) 첨부 서류 (텍스트 파일로 저장되어 AI 맥락에서도 본문이 읽힌다)
    for attach_client, title, doc_type, body in DOCUMENTS:
        doc_id = db.add_text_document(client_id if attach_client else None, title, doc_type,
                                      body + '\n\n' + NOTE, NOTE)
        manifest['documents'].append(doc_id)

    # 6) 작성 중이던 임시저장 (작성실 복구 확인용)
    if not db.get_counseling_draft(owner_id, client_id):
        db.save_counseling_draft(owner_id, client_id, {
            'memo': DRAFT_MEMO, 'html': '', 'text': '', 'date': '2026-09-08', 'method': '전화',
            'template': templates['상담일지 (사례관리양식)']['id'], 'detail': '표준',
            'name': client['name'], 'mask': True,
        })
        manifest['draft'] = [owner_id, client_id]

    # AI 맥락을 다시 만들도록 예약한다.
    with db.get_connection() as conn:
        conn.execute("UPDATE client_context SET revision=revision+1, error='' WHERE client_id=?", (client_id,))


def reset(db, manifest):
    with db.get_connection() as conn:
        for table in ('case_form_records', 'counseling_records', 'case_assessments',
                      'case_goals', 'monitoring_tasks', 'service_links', 'welfare_resources'):
            for row_id in manifest.get(table, []):
                conn.execute(f'DELETE FROM {table} WHERE id=?', (row_id,))
    for doc_id in manifest.get('documents', []):
        db.delete_document(doc_id)
    if manifest.get('draft'):
        owner_id, client_id = manifest['draft']
        with db.get_connection() as conn:
            conn.execute('DELETE FROM counseling_drafts WHERE owner_id=? AND slot=?', (owner_id, str(client_id)))
    previous = manifest.get('case_profile_previous')
    if previous:
        db.save_case_profile(manifest['client_id'], previous['stage'], previous['stage_note'])
    if manifest.get('approval_line_set'):
        with db.get_connection() as conn:
            conn.execute("UPDATE worker_profiles SET approval_line_json='' WHERE id=?",
                         (manifest['approval_line_set'],))
    for profile_id in manifest.get('worker_profiles', []):
        with db.get_connection() as conn:
            current = conn.execute("SELECT value FROM app_preferences WHERE key='current_profile_id'").fetchone()
            if current and int(current[0]) == profile_id:
                print('현재 선택된 사용자가 더미 프로필이라 삭제하지 않았습니다. 다른 사용자로 바꾼 뒤 다시 실행하세요.')
                continue
            conn.execute('DELETE FROM case_form_records WHERE owner_id=?', (profile_id,))
            conn.execute('DELETE FROM form_templates WHERE owner_id=?', (profile_id,))
            conn.execute('DELETE FROM worker_profiles WHERE id=?', (profile_id,))
    with db.get_connection() as conn:
        conn.execute("UPDATE client_context SET revision=revision+1, error='' WHERE client_id=?",
                     (manifest['client_id'],))


def main():
    parser = argparse.ArgumentParser(description='기능 점검용 더미데이터 생성·삭제')
    parser.add_argument('--reset', action='store_true', help='이 스크립트가 넣은 더미데이터만 삭제')
    parser.add_argument('--client-id', type=int, help='대상자 id (기본: 등록된 첫 대상자)')
    parser.add_argument('--no-backup', action='store_true', help='시작 전 백업 ZIP을 만들지 않음')
    args = parser.parse_args()

    data_dir = get_data_dir()
    db = Database(data_dir)
    manifest_path = Path(data_dir) / MANIFEST_NAME
    print('데이터 폴더:', data_dir)

    if args.reset:
        if not manifest_path.exists():
            print('되돌릴 기록이 없습니다:', manifest_path)
            return
        manifest = json.loads(manifest_path.read_text(encoding='utf-8'))
        reset(db, manifest)
        manifest_path.unlink()
        print('더미데이터를 삭제했습니다. 기존 대상자와 기존 기록은 그대로입니다.')
        return

    if manifest_path.exists():
        print('이미 더미데이터가 들어 있습니다. 먼저 --reset 으로 정리한 뒤 다시 실행하세요.')
        return

    clients = db.list_clients()
    if not clients:
        print('등록된 대상자가 없습니다. 대상자를 먼저 추가해 주세요.')
        return
    client_id = args.client_id or clients[0]['id']
    client = db.get_client(client_id)
    if not client:
        print('대상자를 찾지 못했습니다:', client_id)
        return

    if not args.no_backup:
        backup = Path(data_dir) / ('before-dummy-' + datetime.now().strftime('%Y%m%d-%H%M%S') + '.zip')
        ok, message = db.create_full_backup_zip(str(backup))
        print('백업:', message if ok else '실패 · ' + message)
        if not ok:
            return

    manifest = {'created_at': datetime.now().isoformat(timespec='seconds'), 'client_id': client_id,
                'case_form_records': [], 'counseling_records': [], 'case_assessments': [], 'case_goals': [],
                'monitoring_tasks': [], 'service_links': [], 'welfare_resources': [], 'documents': [],
                'worker_profiles': []}
    seed(db, client_id, manifest)
    manifest_path.write_text(json.dumps(manifest, ensure_ascii=False, indent=2), encoding='utf-8')

    print(f"대상자 '{client['name']}'(id={client_id})에 더미데이터를 넣었습니다.")
    for label, key in [('사례관리 서류', 'case_form_records'), ('상담일지', 'counseling_records'),
                       ('사정', 'case_assessments'), ('목표', 'case_goals'), ('모니터링', 'monitoring_tasks'),
                       ('서비스 연계', 'service_links'), ('지역자원', 'welfare_resources'), ('첨부서류', 'documents')]:
        print(f'  - {label}: {len(manifest[key])}건')
    print('  - 되돌리기 기록:', manifest_path)


if __name__ == '__main__':
    main()
