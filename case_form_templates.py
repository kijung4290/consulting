from html import escape


TABLE = '<table border="1" cellspacing="0" cellpadding="6" width="100%" style="border-collapse:collapse;border-color:#849792;">'


class _Form:
    def __init__(self, title, source):
        self.title = title
        self.source = source
        self.fields = []
        self.parts = [f'<h2 style="text-align:center;">{escape(title)}</h2>']

    def token(self, label, hint=""):
        if label not in [field[0] for field in self.fields]:
            self.fields.append((label, hint))
        return "{{" + escape(label) + "}}"

    def rows(self, *fields):
        rows = []
        for field in fields:
            label, hint = field if isinstance(field, tuple) else (field, "")
            rows.append(f'<tr><th width="25%" style="background:#eaf1ee;">{escape(label)}</th><td>{self.token(label, hint)}</td></tr>')
        self.parts.append(TABLE + "".join(rows) + "</table><p></p>")
        return self

    def grid(self, title, columns, count=3):
        self.parts.append(f"<h3>{escape(title)}</h3>" + TABLE)
        self.parts.append("<tr>" + "".join(f'<th style="background:#eaf1ee;">{escape(c)}</th>' for c in columns) + "</tr>")
        for row in range(1, count + 1):
            self.parts.append("<tr>" + "".join(
                f'<td>{self.token(f"{title} {column}") if row == 1 else "&nbsp;"}</td>' for column in columns
            ) + "</tr>")
        self.parts.append("</table><p></p>")
        return self

    def note(self, text):
        self.parts.append(f"<p>{escape(text)}</p>")
        return self

    def template(self):
        guide = (
            f"상담 메모를 [{self.title}]에 맞춰 작성하십시오.\n"
            "입력에 없는 정보는 빈칸으로 두십시오. 이름·날짜·번호·점수·진단을 추측하지 마십시오.\n"
            "동의 여부, 서명 및 날인은 작성하지 마십시오. 대상자의 마스킹을 유지하십시오.\n"
            "확인된 내용이 있는 항목만 아래 항목명 그대로 출력하십시오. 빈 항목은 생략하십시오.\n"
            "반복표는 첫 행에 자동 입력됩니다. 여러 사람·목표·서비스는 각 열에서 동일한 순서로 줄바꿈하여 기록하십시오.\n\n"
            f"[출력 양식]\n### [{self.title}]\n"
        )
        guide += "\n".join(f"{i}. **{label}**: {hint}" for i, (label, hint) in enumerate(self.fields, 1))
        return {
            "category": "사례관리양식",
            "description": f"참고: 사례관리양식/{self.source}. 원본 항목을 재구성한 편집용 표 양식입니다.",
            "guide": guide,
            "form_html": '<div style="font-family:Malgun Gothic;color:#1f2937;">' + "".join(self.parts) + "</div>",
            "example_input": "",
        }


